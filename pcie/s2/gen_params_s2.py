#!/usr/bin/env python3
"""Stage-2 PCIE_2_1 parameters = the factory design's (../factory_params.vh) with the link limited to Gen1:
max/target link speed 2.5 GT/s and the core clock at 250 MHz (USER_CLK_FREQ 3; USER_CLK2_DIV2 stays, so the user
interface is 128 bits at 125 MHz, pg054 Table 8). Writes s2_params.vh (`PCIE_2_1_S2_PARAMS)."""
import re

OVERRIDE = {
    "LINK_CAP_MAX_LINK_SPEED": "4'h1",
    "LINK_CTRL2_TARGET_LINK_SPEED": "4'h1",
    "USER_CLK_FREQ": "3'h3",
    "ALLOW_X8_GEN2": '"FALSE"',
}
src = open("../factory_params.vh").read()
block = re.search(r"`define PCIE_2_1_FACTORY_PARAMS \\\n(.*?)(?:\n\n|\Z)", src, re.S).group(1)
params = re.findall(r"\.(\w+)\(([^)]*)\)", block)
seen = set()
out = []
for name, val in params:
    if name in OVERRIDE:
        val = OVERRIDE[name]; seen.add(name)
    out.append(f"    .{name}({val})")
missing = set(OVERRIDE) - seen
if missing:
    raise SystemExit(f"not in the factory parameters: {missing}")
open("s2_params.vh", "w").write(
    "// generated by gen_params_s2.py: factory PCIE_2_1 parameters, Gen1 only (" +
    ", ".join(f"{k}={v}" for k, v in OVERRIDE.items()) + ")\n"
    "`define PCIE_2_1_S2_PARAMS \\\n" + ",\\\n".join(out) + "\n")
print(f"{len(out)} parameters, {len(OVERRIDE)} changed")
