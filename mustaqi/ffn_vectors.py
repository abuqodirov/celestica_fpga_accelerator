#!/usr/bin/env python3
"""Test data for the FPGA FFN unit (accel/rtl/ffn_unit.v), from its bit-exact spec fpga_llm.silu_mul_hw + the golden
MXINT8 quantizer (fpga_llm.quantize):

  ffn_vectors.py tables              regenerate accel/rtl/ffn_tables.vh (the unit's float32 tables)
  ffn_vectors.py random <file>       random gate/up rows: realistic magnitudes, outliers, zeros, the |t| >= 64 cut-offs
  ffn_vectors.py real <file> [--tokens 2]   gate_up results of every layer for real tokens (CPU backend, heavy)

File: int32 count, then per case: int32 nrows, float32 g[nrows], float32 u[nrows], float32 h[nrows] (silu_mul_hw),
uint32 img[nrows/4 + nrows/32] (the activation image the unit must write into the engines)."""
import os
import struct
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fpga_llm as F  # noqa: E402


def tables():
    out = ["// ffn_tables.vh - generated by mustaqi/ffn_vectors.py tables (from fpga_llm.py) - float32 tables",
           "// of silu_mul (ffn_unit.v). T[i] = 2^(i/64), D[i] = T[i+1] - T[i], R[j] = 1/(1 + j/64), DR[j] = R[j+1] - R[j].",
           "function [63:0] tab_td(input [5:0] i);   // {D[i], T[i]}", "    case (i)"]
    for i in range(64):
        out.append(f"    6'd{i}: tab_td = 64'h{int(F._D[i].view(np.uint32)):08x}{int(F._T[i].view(np.uint32)):08x};")
    out += ["    endcase", "endfunction", "function [63:0] tab_rdr(input [5:0] j);   // {DR[j], R[j]}", "    case (j)"]
    for j in range(64):
        out.append(f"    6'd{j}: tab_rdr = 64'h{int(F._DR[j].view(np.uint32)):08x}{int(F._R[j].view(np.uint32)):08x};")
    out += ["    endcase", "endfunction", ""]
    open(os.path.join(HERE, "..", "accel", "rtl", "ffn_tables.vh"), "w").write("\n".join(out))


def write(path, cases):
    with open(path, "wb") as f:
        f.write(struct.pack("<i", len(cases)))
        for g, u in cases:
            g, u = g.astype(np.float32), u.astype(np.float32)
            h = F.silu_mul_hw(g, u)
            img = F.quantize(h)[3]
            f.write(struct.pack("<i", len(g)) + g.tobytes() + u.tobytes() + h.astype(np.float32).tobytes() +
                    img.astype(np.uint32).tobytes())
    print(f"{path}: {len(cases)} cases, {sum(len(g) for g, _ in cases)} rows")


def engine_like(rng, n):
    """values on the engines' output grid (multiples of 2^-30), log-uniform magnitudes 2^-30 .. ~100"""
    v = rng.standard_normal(n) * 10.0 ** rng.uniform(-6, 1.5, n)
    v[rng.random(n) < 0.01] *= 30                                     # outliers
    v[rng.random(n) < 0.01] = 0
    return (np.round(v * 2.0 ** 30) / 2.0 ** 30).astype(np.float32)


def random_cases():
    rng = np.random.default_rng(5)
    cases = [(engine_like(rng, F.FFN), engine_like(rng, F.FFN)) for _ in range(3)]
    # cut-offs and special values: t = g * -log2(e) around +-64 (g ~ -+44.36), zeros, the smallest values
    sp = np.array([0, -0.0, 2.0 ** -30, -2.0 ** -30, 44.3614, -44.3614, 44.3615, -44.3615, 44.36, -44.37, 50, -50,
                   1, -1, 0.5, 1e-6, -1e-6, 88, -88, 3, -3, 7.5, -7.5, 0.25, 2.0 ** -20, 12, -12, 30, -30, 0.1, -0.1,
                   0.7], np.float32)
    g = np.tile(sp, 8)
    u = np.tile(np.array([1, -1, 2.0 ** -30, 100, 0.001, -3, 0, 7] * 4, np.float32), 8)[:len(g)]
    cases.append((g, u))
    cases.append((np.full(64, -60, np.float32), np.ones(64, np.float32)))   # all h = 0: subgroup e = 0
    # quantizer ties: g = 64 (sigmoid = 1, h = 64 * u exactly); group max 127 -> e = 0, the others k + 0.5
    u = np.array([127] + [k + 0.5 for k in range(31)], np.float32) / 64
    u2 = np.array([63.5] + [k + 0.5 for k in range(31)], np.float32) / 64    # max 63.5 = 127 * 2^-1: exponent edge
    cases.append((np.full(64, 64, np.float32), np.concatenate([u, -u2])))
    # fixed-point ties of t * 2^22: |t| in [1, 2) has one bit below 2^-22, odd mantissas are ties
    g = (rng.uniform(1, 2, 4096) / 1.4426950408889634 * rng.choice([-1, 1], 4096)).astype(np.float32)
    cases.append((g, engine_like(rng, 4096)))
    return cases


def real_cases(tokens):
    """gate_up results of all 36 layers for the first `tokens` tokens of eval_uz.txt (CPU backend = engine arithmetic)"""
    from tokenizers import Tokenizer
    tok = Tokenizer.from_file(os.path.join(HERE, "hf", "tokenizer.json"))
    ids = tok.encode(open(os.path.join(HERE, "eval_uz.txt")).read(), add_special_tokens=False).ids[:tokens]
    cpu = F.CpuBackend(F.Index())
    cases = []

    class Tap:
        def mv_q(self, name, q):
            y = cpu.mv_q(name, q)
            if name.endswith("gate_up"):
                cases.append((y[:F.FFN].copy(), y[F.FFN:].copy()))
            return y

    model = F.Model(Tap(), ctx=tokens + 1, ffn_hw=True)
    for t in ids:
        model.forward(t, logits=False)
    return cases


def main():
    if sys.argv[1] == "tables":
        tables()
    elif sys.argv[1] == "random":
        write(sys.argv[2], random_cases())
    elif sys.argv[1] == "real":
        n = int(sys.argv[sys.argv.index("--tokens") + 1]) if "--tokens" in sys.argv else 2
        write(sys.argv[2], real_cases(n))


if __name__ == "__main__":
    main()
