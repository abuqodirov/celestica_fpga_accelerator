#!/usr/bin/env python3
"""Generate build/minirv_core.v from the untouched ../top.v for synthesis and our testbench.

- renames module `top` -> `minirv_core`
- removes the simulation-only DPI-C imports and calls (halt_sim, notify_retire)
- adds two debug outputs: dbg_a0 (register a0) and dbg_ebreak (an ebreak retired this cycle)
"""
import re
import sys

src = open(sys.argv[1] if len(sys.argv) > 1 else "../top.v").read()
out = re.sub(r"\bmodule\s+top\s*\(", "module minirv_core(", src, count=1)
out = re.sub(r'^\s*import\s+"DPI-C".*?;\s*$', "", out, flags=re.M)
out = out.replace("halt_sim(a0_value);", "")
out = out.replace("notify_retire();", ";")
out = re.sub(r"(output\s+\[6:0\]\s+funct7_out)", r"\1,\n        output [31:0] dbg_a0,\n        output dbg_ebreak", out, count=1)
out = re.sub(r"\bendmodule\b", "        assign dbg_a0 = a0_value;\n        assign dbg_ebreak = is_ebreak && inst_retired;\nendmodule", out, count=1)
for bad in ("DPI-C", "halt_sim", "notify_retire"):
    assert bad not in out, bad
open(sys.argv[2] if len(sys.argv) > 2 else "build/minirv_core.v", "w").write(
    "// GENERATED by prep_core.py from minirv/top.v -- do not edit\n" + out)
